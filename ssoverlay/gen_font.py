#!/usr/bin/env python3
"""Generate font_data.h for ssoverlay from the native 28px UI font (ui_zh).

Adds procedural glyphs the native font lacks: U+00B0 (degree ring),
U+25CF (filled disc, used as a status dot) and U+25B2 (triangle, altitude).
"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lvfont import Font, FONTS  # noqa: E402

CHARS = ("0123456789 .:-/+()" "ABCDEFGHIJKLMNOPQRSTUVWXYZ" "abcdefghijklmnopqrstuvwxyz"
         "方位速度时纬经定无有效信号北南东西卫星正在未")


def ring(d, stroke):
    r_out = d / 2
    r_in = r_out - stroke
    px = []
    for y in range(d):
        for x in range(d):
            # 4x4 supersampling
            hit = 0
            for sy in range(4):
                for sx in range(4):
                    dx = x + (sx + 0.5) / 4 - r_out
                    dy = y + (sy + 0.5) / 4 - r_out
                    rr = math.hypot(dx, dy)
                    hit += r_in <= rr <= r_out
            px.append(round(255 * hit / 16))
    return px


def triangle(w, h):
    px = []
    for y in range(h):
        for x in range(w):
            hit = 0
            for sy in range(4):
                for sx in range(4):
                    fx, fy = x + (sx + 0.5) / 4, y + (sy + 0.5) / 4
                    hit += abs(fx - w / 2) <= fy / h * w / 2
            px.append(round(255 * hit / 16))
    return px


def big_digits(f, scale=0.36):
    """Native speed-saver digit images (91x210 ARGB, table 0x19db840) downscaled
    with area averaging. Returned as glyphs U+E030..U+E039 whose baseline is the
    bottom of the digit shape."""
    tbl = f._u("<10I", 0x19DB840)
    out = []
    for d, dscp in enumerate(tbl):
        hdr, size, data = f._u("<3I", dscp)
        W, H = (hdr >> 10) & 0x7FF, (hdr >> 21) & 0x7FF
        px = f.b[data - 0x10000:data - 0x10000 + size]
        cov = [px[i * 4 + 3] * px[i * 4 + 1] / 255 for i in range(W * H)]
        w, h = math.ceil(W * scale), math.ceil(H * scale)
        a = []
        for y in range(h):
            y0, y1 = y / scale, (y + 1) / scale
            for x in range(w):
                x0, x1 = x / scale, (x + 1) / scale
                acc = 0.0
                for sy in range(int(y0), min(H, math.ceil(y1))):
                    fy = min(y1, sy + 1) - max(y0, sy)
                    for sx in range(int(x0), min(W, math.ceil(x1))):
                        fx = min(x1, sx + 1) - max(x0, sx)
                        acc += cov[sy * W + sx] * fx * fy
                a.append(min(255, round(acc * scale * scale)))
        bottom = 187 * scale          # digit shape ends at row 186 of 210
        adv16 = round((W + 13) * scale * 16)   # native spacing: 13 px between digits
        out.append((0xE030 + d, {"adv16": adv16, "w": w, "h": h, "ox": 0,
                                 "oy": round(bottom) - h, "a": a}))
    return out


def main(out):
    f = Font(FONTS["ui_zh"])
    glyphs = []
    for ch in CHARS:
        g = f.glyph(ch)
        if g is None:
            raise SystemExit(f"missing glyph {ch!r}")
        glyphs.append((ord(ch), g))
    digit = f.glyph("0")
    # Degree: ring ~9px, top aligned with digit top.
    d = 9
    glyphs.append((0xB0, {"adv16": (d + 3) * 16, "w": d, "h": d, "ox": 1,
                          "oy": digit["oy"] + digit["h"] - d, "a": ring(d, 2.0)}))
    # Status dot: 14px disc centred on x-height.
    d = 14
    glyphs.append((0x25CF, {"adv16": (d + 4) * 16, "w": d, "h": d, "ox": 1,
                            "oy": digit["oy"] + (digit["h"] - d) // 2, "a": ring(d, d / 2)}))
    # Altitude mark: 16x13 triangle centred on the digit height.
    w, h = 16, 13
    glyphs.append((0x25B2, {"adv16": (w + 4) * 16, "w": w, "h": h, "ox": 1,
                            "oy": digit["oy"] + (digit["h"] - h) // 2, "a": triangle(w, h)}))
    glyphs += big_digits(f)
    glyphs.sort()
    codes = [c for c, _ in glyphs]
    kerns = []
    for a in CHARS:
        for b in CHARS:
            k = f.kerning(a, b)
            if k:
                kerns.append((ord(a), ord(b), k))
    data = []
    lines = ["/* Generated by gen_font.py from main_app font 0x19fea6c (ui_zh). Do not edit. */",
             f"#define FONT_LINE_HEIGHT {f.line_height}", f"#define FONT_BASE_LINE {f.base_line}",
             "struct glyph { unsigned cp; short adv16; unsigned char w, h; signed char ox, oy; unsigned off; };",
             "static const struct glyph GLYPHS[] = {"]
    for c, g in glyphs:
        lines.append(f"  {{0x{c:x}, {g['adv16']}, {g['w']}, {g['h']}, {g['ox']}, {g['oy']}, {len(data)}}},")
        data.extend(g["a"])
    lines.append("};")
    lines.append(f"#define NGLYPHS {len(glyphs)}")
    lines.append("struct kern { unsigned a, b; int k16; };")
    lines.append("static const struct kern KERNS[] = {")
    lines += [f"  {{0x{a:x}, 0x{b:x}, {k}}}," for a, b, k in kerns] or ["  {0, 0, 0},"]
    lines.append("};")
    lines.append(f"#define NKERNS {len(kerns)}")
    lines.append("static const unsigned char ALPHA[] = {")
    for i in range(0, len(data), 32):
        lines.append("  " + ",".join(str(v) for v in data[i:i + 32]) + ",")
    lines.append("};")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"{out}: {len(glyphs)} glyphs, {len(kerns)} kern pairs, {len(data)} alpha bytes", file=sys.stderr)
    assert codes == sorted(codes)


if __name__ == "__main__":
    main(sys.argv[1])
