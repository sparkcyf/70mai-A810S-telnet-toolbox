#!/usr/bin/env python3
"""Generate fingerprint.h: code/literal words of main_app that ssoverlay's
hard-coded addresses depend on. ssoverlay compares them against the live
process and refuses to run on a different build."""
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lvfont import ELF  # noqa: E402
RANGES = [
    (0xB8DAF4, 4),   # lv_disp_get_default + literal -> disp_def 0x2a271b8
    (0xB5A1E4, 4),   # lv_disp_get_scr_act: act_scr at +0x44
    (0xB5D9FC, 4),   # lv_obj_set_hidden: flags byte +0x40 bit4
    (0x41F44, 5),    # UI speed getter (+0x124) + literal
    (0x48F44, 6),    # param getter (param 56)
    (0x9DACC, 6),    # update_speed_display literals (saver object globals)
    (0x9DFC0, 4),    # page_open literals
    (0xF05A0, 8),    # memcpy of parsed NMEA batch to 0x1b44228
    (0xF12A0, 1),    # its literal
    (0xF33D0, 4),    # RMC: valid flag / lat {value, scale} at +0x20
]
b = ELF.read_bytes()
lines = ["/* Generated by gen_fingerprint.py. Do not edit. */",
         "struct fp { unsigned addr, val; };", "static const struct fp FINGERPRINT[] = {"]
n = 0
for va, cnt in RANGES:
    for i in range(cnt):
        a = va + 4 * i
        lines.append(f"  {{0x{a:x}, 0x{struct.unpack_from('<I', b, a - 0x10000)[0]:08x}}},")
        n += 1
lines += ["};", f"#define NFINGERPRINT {n}"]
Path(sys.argv[1]).write_text("\n".join(lines) + "\n")
print(f"{sys.argv[1]}: {n} words", file=sys.stderr)
